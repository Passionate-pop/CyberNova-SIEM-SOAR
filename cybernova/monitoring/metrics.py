# --- Simple metrics tracking for pipeline ---
_pipeline_metrics = {
    "ingestion_total": 0,
    "ingestion_deduped": 0,
    "ingestion_failed": 0,
    "correlation_triggers": 0,
    "risk_escalations": 0,
    "risk_confirmations": 0,
    "soar_triggered": 0,
    "soar_blocked": 0,
}


def track_ingestion(ingested=True, deduped=False, failed=False):
    """Track ingestion events."""
    if ingested:
        _pipeline_metrics["ingestion_total"] += 1
    if deduped:
        _pipeline_metrics["ingestion_deduped"] += 1
    if failed:
        _pipeline_metrics["ingestion_failed"] += 1


def track_correlation():
    """Track correlation triggers."""
    _pipeline_metrics["correlation_triggers"] += 1


def track_risk(escalated=False, confirmed=False):
    """Track risk events."""
    if escalated:
        _pipeline_metrics["risk_escalations"] += 1
    if confirmed:
        _pipeline_metrics["risk_confirmations"] += 1


def track_soar(triggered=False):
    """Track SOAR events."""
    if triggered:
        _pipeline_metrics["soar_triggered"] += 1
    else:
        _pipeline_metrics["soar_blocked"] += 1


def get_pipeline_metrics():
    """Get pipeline metrics."""
    return {
        "ingestion": {
            "total": _pipeline_metrics["ingestion_total"],
            "deduped": _pipeline_metrics["ingestion_deduped"],
            "failed": _pipeline_metrics["ingestion_failed"],
        },
        "correlation": {
            "triggers": _pipeline_metrics["correlation_triggers"],
        },
        "risk": {
            "escalations": _pipeline_metrics["risk_escalations"],
            "confirmations": _pipeline_metrics["risk_confirmations"],
        },
        "soar": {
            "triggered": _pipeline_metrics["soar_triggered"],
            "blocked": _pipeline_metrics["soar_blocked"],
        },
    }
